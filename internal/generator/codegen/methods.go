const (
	// methodFilePrefix - методы лежат в пакете процесса файлами method_<id задачи>.go
	methodFilePrefix = "method_"
	generatedHeader  = "// Code generated by go-bpm-gen. DO NOT EDIT."
)

type methodFile struct {
	dataImports
	Package   string
	FuncName  string
	ElementId string
	Name      string
}

type scriptMethodFile struct {
	dataImports
	Package   string
	FuncName  string
	ElementId string
	Name      string
	// Code - код скрипта на модели данных; при resultVariable - присваивание результата полю
	Code           string
	ResultVariable string
}

// prepareMethodFiles генерирует processPath/method_<id задачи>.go:
//   - для scriptTask — метод с кодом из процесса на модели данных, перегенерируется при каждом запуске;
//   - для task — заглушку на модели данных и клиентах (imports), которая пишется руками,
//     поэтому существующие файлы не перезаписываются и не удаляются.
func prepareMethodFiles(process *bpmn.Process, processPath string, pkg string, imports dataImports, m *modelPackage, gaps *modelGaps) error {
	if err := prepareScriptMethodFiles(process, processPath, pkg, imports, m, gaps); err != nil {
		return err
	}
	return prepareMethodStubFiles(process, processPath, pkg, imports)
}

func methodFilePath(dir string, taskId string) string {
	return filepath.Join(dir, methodFilePrefix+utils.ToSnakeCase(taskId)+".go")
}

func prepareScriptMethodFiles(process *bpmn.Process, dir string, pkg string, imports dataImports, m *modelPackage, gaps *modelGaps) error {
	t, err := template.New("script_method").Parse(templates.ScriptMethodTemplate)
	if err != nil {
		return err
	}

	for _, task := range process.GetScriptTasks() {
		path := methodFilePath(dir, task.Id)
		// Сгенерированные файлы уже удалены, значит существующий файл написан руками
		if exists, err := fileExists(path); err != nil {
			return err
		} else if exists {
			return fmt.Errorf("script task %s: %s написан руками, удалите его, чтобы сгенерировать скрипт", task.Id, path)
		}

		script := task.GetScript()
		ctx := exprContext{model: m, gaps: gaps, owner: "процесс " + process.Id + ": скрипт " + task.Id}
		gapsBefore := gaps.len()
		code, err := scriptCode(ctx, removeFirstEqual(strings.TrimSpace(script.Expression)), script.ResultVariable)
		if err != nil {
			return fmt.Errorf("script task %s: %w", task.Id, err)
		}
		if gaps.len() > gapsBefore {
			continue
		}

		var buf bytes.Buffer
		err = t.Execute(&buf, scriptMethodFile{
			dataImports:    imports,
			Package:        pkg,
			FuncName:       utils.ToPascalCase(task.Id),
			ElementId:      task.Id,
			Name:           strings.Join(strings.Fields(task.Name), " "),
			Code:           code,
			ResultVariable: script.ResultVariable,
		})
		if err != nil {
			return err
		}

		if err := utils.SaveGoFile(path, buf.Bytes()); err != nil {
			return fmt.Errorf("script task %s: %w", task.Id, err)
		}
	}
	return nil
}

func prepareMethodStubFiles(process *bpmn.Process, dir string, pkg string, imports dataImports) error {
	t, err := template.New("method").Parse(templates.MethodTemplate)
	if err != nil {
		return err
	}

	for _, task := range process.GetMethodTasks() {
		path := methodFilePath(dir, task.Id)
		if exists, err := fileExists(path); err != nil {
			return err
		} else if exists {
			continue
		}

		var buf bytes.Buffer
		err := t.Execute(&buf, methodFile{
			dataImports: imports,
			Package:     pkg,
			FuncName:    utils.ToPascalCase(task.Id),
			ElementId:   task.Id,
			Name:        strings.Join(strings.Fields(task.Name), " "),
		})
		if err != nil {
			return err
		}

		if err := utils.SaveGoFile(path, buf.Bytes()); err != nil {
			return fmt.Errorf("method %s: %w", task.Id, err)
		}
	}
	return nil
}

// removeGeneratedFiles удаляет из dir файлы с заголовком generatedHeader, файлы без него не трогает
func removeGeneratedFiles(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".go" {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(content, []byte(generatedHeader)) {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	return nil
}

func fileExists(path string) (bool, error) {
	_, err := os.Stat(path)
	if err == nil {
		return true, nil
	}
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	return false, err
}

// scriptCode - код метода scriptTask на модели данных.
// С resultVariable скрипт - выражение: его переменные строго переводятся в поля модели, результат
// присваивается полю resultVariable. Без resultVariable скрипт - код Go: в поля модели переводятся
// только имена, которые есть в DataModel, остальное (пакеты, локальные переменные) остаётся как есть
func scriptCode(ctx exprContext, expression, resultVariable string) (string, error) {
	if expression == "" {
		return "", nil
	}
	if resultVariable == "" {
		return rewriteScript(ctx, expression), nil
	}
	segments, ok := splitPath(resultVariable)
	if !ok {
		return "", fmt.Errorf("resultVariable %q - не имя переменной", resultVariable)
	}
	value, err := ctx.rewrite(expression, kindUnknown)
	if err != nil {
		return "", err
	}
	path, gap := ctx.model.resolvePath(segments)
	if gap != nil {
		ctx.gaps.add(ctx.owner, *gap, kindGoType(expressionKind(expression)))
		return "", nil
	}
	return path.String() + " = " + value, nil
}

// rewriteScript переводит в поля модели имена в коде Go скрипта, которые есть в DataModel.
// Код, который не разбирается, остаётся как есть: ошибку покажет проверка сборки
func rewriteScript(ctx exprContext, code string) string {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "", "package p\nfunc _() {\n"+code+"\n}", parser.SkipObjectResolution)
	if err != nil {
		return code
	}
	body := file.Decls[0].(*ast.FuncDecl).Body
	locals := localDeclarations(code)
	astutil.Apply(body, func(cursor *astutil.Cursor) bool {
		switch cursor.Name() {
		case "Sel", "Key":
			return false
		}
		node, ok := cursor.Node().(ast.Expr)
		if !ok {
			return true
		}
		segments := chainSegments(node)
		if segments == nil {
			return true
		}
		if locals[segments[0]] || isPredeclared(segments[0]) {
			return false
		}
		if _, isField := ctx.model.field(dataModelType, segments[0]); !isField {
			return false
		}
		path, gap := ctx.model.resolvePath(segments)
		if gap != nil {
			ctx.gaps.add(ctx.owner, *gap, "any")
			return false
		}
		cursor.Replace(path.expr)
		return false
	}, nil)
	var lines []string
	for _, stmt := range body.List {
		var buf bytes.Buffer
		if err := format.Node(&buf, fset, stmt); err != nil {
			return code
		}
		lines = append(lines, buf.String())
	}
	return strings.Join(lines, "\n")
}
