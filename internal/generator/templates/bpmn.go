package templates

// BpmnTemplate - process/bpmn-gen.go: BPMN- и DMN-файлы папки process вшиты через go:embed без копирования.
// Файл лежит в самой папке process, потому что go:embed не берёт файлы выше своего пакета
const BpmnTemplate = `// Code generated by go-bpm-gen. DO NOT EDIT.

package {{ .Package }}

import "embed"

//go:embed{{ range .Files }} {{ printf "%q" . }}{{ end }}{{ range .DmnFiles }} {{ printf "%q" . }}{{ end }}
var files embed.FS

// BPMN - BPMN-файлы по пути относительно этой папки, по ним движок рисует диаграмму с историей экземпляра
var BPMN = readFiles({{ range $i, $file := .Files }}{{ if $i }}, {{ end }}{{ printf "%q" $file }}{{ end }})

// DMN - DMN-файлы по пути относительно этой папки, по ним страница истории показывает сработавшие правила
var DMN = readFiles({{ range $i, $file := .DmnFiles }}{{ if $i }}, {{ end }}{{ printf "%q" $file }}{{ end }})

func readFiles(names ...string) map[string]string {
	result := make(map[string]string, len(names))
	for _, name := range names {
		data, err := files.ReadFile(name)
		if err != nil {
			panic(err)
		}
		result[name] = string(data)
	}
	return result
}
`
