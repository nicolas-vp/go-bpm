package templates

// ProcessTemplate - flow процесса; условия и методы лежат в том же пакете, поэтому из целевого проекта
// импортируется только пакет сервисов: методы task получают их через bpm.Method
const ProcessTemplate = `// Code generated by go-bpm-gen. DO NOT EDIT.

package {{ .Package }}

import (
{{- if .HasTimers }}
	"time"
{{ end }}
	"` + ModelImport + `"
	"{{ .ServicesImport }}"
)

// Deployment - flow процесса и его подпроцессов; методы task получают сервисы svc
func Deployment(svc *services.Services) map[string]bpm.DeploymentProcess {
	return map[string] bpm.DeploymentProcess{ {{range $process := .Processes}}
	"{{ $process.ProcessID }}" : {
		StartElement: "{{ $process.StartElement }}",
		Expressions:  map[string]*bpm.Expression{ {{range $id, $expr := $process.Expressions}}
			"{{ $expr.ElementId }}": {
				ElementId:            "{{ $expr.ElementId }}",
				ActivateType:         bpm.ActivateType{{ activateType $expr.ActivateType }},
				CompleteType:         bpm.CompleteType{{ completeType $expr.CompleteType }},
				NextElements:         []string{ {{join $expr.NextElements ", "}} },
				{{- if $expr.ConditionFunc }}
				Condition:            bpm.Condition({{ $expr.ConditionFunc }}),
				{{- end }}
				{{- if $expr.MethodFunc }}
				Method:               bpm.Method(svc, {{ $expr.MethodFunc }}),
				{{- end }}
				{{- if $expr.ProcessId }}
				ProcessId:            "{{ $expr.ProcessId }}",
				{{- end }}
				{{- if $expr.TaskType }}
				TaskType:             "{{ $expr.TaskType }}",
				{{- end }}
				{{- if $expr.ParallelSyncQuantity }}
				ParallelSyncQuantity: {{ $expr.ParallelSyncQuantity }},
				{{- end }}
				{{- if $expr.PropagateChildVariables }}
				PropagateChildVariables: true,
				{{- end }}
				{{- if $expr.Timer }}
				Timer:                {{ duration $expr.Timer }},
				{{- end }}
				{{- if $expr.TimerDate }}
				TimerDate:            {{ printf "%q" $expr.TimerDate }},
				{{- end }}
				{{- if $expr.Boundaries }}
				Boundaries: []bpm.Boundary{ {{range $b := $expr.Boundaries}}
					{ElementId: "{{ $b.ElementId }}", Type: bpm.BoundaryType{{ boundaryType $b.Type }}
					{{- if $b.Timer }}, Timer: {{ duration $b.Timer }}{{ end }}
					{{- if $b.TimerDate }}, TimerDate: {{ printf "%q" $b.TimerDate }}{{ end }}
					{{- if $b.ErrorCode }}, ErrorCode: {{ printf "%q" $b.ErrorCode }}{{ end }}}, {{end}}
				},
				{{- end }}
				{{- with $expr.UserTask }}
				UserTask: &bpm.UserTask{
					{{- if .Name }}
					Name:            {{ printf "%q" .Name }},
					{{- end }}
					{{- if .Assignee }}
					Assignee:        {{ printf "%q" .Assignee }},
					{{- end }}
					{{- if .CandidateUsers }}
					CandidateUsers:  []string{ {{ quotes .CandidateUsers }} },
					{{- end }}
					{{- if .CandidateGroups }}
					CandidateGroups: []string{ {{ quotes .CandidateGroups }} },
					{{- end }}
					{{- if .FormKey }}
					FormKey:         {{ printf "%q" .FormKey }},
					{{- end }}
				},
				{{- end }}
				{{- with $expr.Message }}
				Message: &bpm.Message{
					Name:           {{ printf "%q" .Name }},
					{{- if .CorrelationKey }}
					CorrelationKey: {{ printf "%q" .CorrelationKey }},
					{{- end }}
				},
				{{- end }}
				{{- with $expr.Loop }}
				Loop: &bpm.Loop{
					{{- if .Cardinality }}
					Cardinality:         {{ .Cardinality }},
					{{- end }}
					{{- if .ConditionFunc }}
					CompletionCondition: bpm.LoopCondition({{ .ConditionFunc }}),
					{{- end }}
				},
				{{- end }}
			}, {{end}}
		},
	},  {{end}}
	}
}
`
